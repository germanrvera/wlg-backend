    def handle(self, *args, **options):
        from django.utils.text import slugify as _slugify
        self.stdout.write(self.style.SUCCESS('Cargando datos iniciales...'))

        new_slugs = {_slugify(d['nombre']) for d in FAMILIAS_DATA}

        # Remove stale families not in new list
        stale = FamiliaProducto.objects.exclude(slug__in=new_slugs)
        stale_count = stale.count()
        if stale_count:
            stale.delete()
            self.stdout.write(f'✗ Familias obsoletas eliminadas: {stale_count}')

        for data in FAMILIAS_DATA:
            familia, created = FamiliaProducto.objects.update_or_create(
                slug=_slugify(data['nombre']),
                defaults={
                    'nombre': data['nombre'],
                    'macro': data['macro'],
                    'tipo': data['tipo'],
                    'descripcion': data['descripcion'],
                    'skus': data['skus'],
                    'photo': data['photo'],
                    'filter_ct': data['filter_ct'],
                    'filter_ip': data['filter_ip'],
                    'filter_dim_sys': data['filter_dim_sys'],
                    'filter_cri': data['filter_cri'],
                    'filter_v': data['filter_v'],
                    'filter_w': data['filter_w'],
                    'filter_ubicacion': data['filter_ubicacion'],
                    'filter_aplicacion': data['filter_aplicacion'],
                    'filter_montaje': data['filter_montaje'],
                    'has_dim': data['has_dim'],
                    'orden': data['orden'],
                }
            )
